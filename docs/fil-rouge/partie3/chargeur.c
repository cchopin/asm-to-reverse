#include <stdio.h>
#include <string.h>
#include <sys/mman.h>

static const unsigned char charge[] = {
    0xef, 0x1f, 0xad, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xf7, 0xef,
    0x1f, 0xc4, 0xcf, 0xce, 0xc1, 0xc1, 0xd5, 0xc2, 0xda, 0xf7, 0xef, 0x1f,
    0xd5, 0xc0, 0xc2, 0xd2, 0xd5, 0xf8, 0xc3, 0xc2, 0xf7, 0xef, 0x1f, 0xe1,
    0xeb, 0xe6, 0xe0, 0xdc, 0xc4, 0xcf, 0xc6, 0xf7, 0x96, 0x67, 0x58, 0x67,
    0x2e, 0x60, 0xef, 0x2e, 0x41, 0xcd, 0xbe, 0xfd, 0xa8, 0xa2, 0xcd, 0x9b,
    0xff, 0x96, 0x58, 0xa8, 0xa2
};

int main(void)
{
    size_t n = sizeof(charge);
    unsigned char *zone = mmap(NULL, 4096, PROT_READ | PROT_WRITE,
                               MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (zone == MAP_FAILED)
        return 1;

    for (size_t i = 0; i < n; i++)
        zone[i] = charge[i] ^ 0xA7;

    /* la zone devient exécutable, mais n'est plus modifiable */
    if (mprotect(zone, 4096, PROT_READ | PROT_EXEC) != 0)
        return 1;

    puts("Chargement termine.");
    fflush(stdout);
    ((void (*)(void))zone)();
    return 0;
}
