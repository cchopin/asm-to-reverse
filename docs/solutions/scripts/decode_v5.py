def dec(octets, cle=0x37):
    """Meme algorithme que la fonction du binaire : XOR 0x37 jusqu'a obtenir 0."""
    out = bytearray()
    for b in octets:
        c = b ^ cle
        if c == 0:
            break
        out.append(c)
    return out.decode()


def decode_cache(texte_hex, cle=0x42):
    """Inverse de encoder_hex : hexa -> octets, XOR avec une cle qui augmente de 1."""
    data = bytes.fromhex(texte_hex.strip())
    out = bytearray()
    for b in data:
        out.append(b ^ cle)
        cle = (cle + 1) & 0xff
    return out.decode(errors='replace')


