/* packed : demo pedagogique de packer (zlib). Le vrai code est compresse,
   decompresse en memoire a l'execution, puis execute. Imite un binaire packe. */
#include <stdio.h>
#include <string.h>
#include <zlib.h>
#include <sys/mman.h>
static const unsigned char blob[] = {
    0x78, 0xda, 0x7b, 0x2d, 0x1c, 0xb7, 0x83, 0x91, 0x81, 0x81, 0x61, 0x3f,
    0x88, 0xd8, 0xa5, 0x0e, 0x24, 0xf8, 0x59, 0x0f, 0xbf, 0x78, 0xf1, 0xff,
    0xff, 0xff, 0xe4, 0xfc, 0x94, 0x54, 0x85, 0xfc, 0xa2, 0xcc, 0xf4, 0xcc,
    0xbc, 0xc4, 0x1c, 0x85, 0xd4, 0x8a, 0xd4, 0xe4, 0xd2, 0x92, 0x54, 0x2b,
    0x05, 0x37, 0x1f, 0x47, 0xf7, 0xea, 0x94, 0xd4, 0x82, 0xc4, 0xe4, 0xec,
    0xf8, 0xfc, 0xec, 0x5a, 0x2e, 0x00, 0xed, 0x0c, 0x17, 0x95};
int main(void){
    uLongf n = 65;
    unsigned char *z = mmap(NULL, 4096, PROT_READ|PROT_WRITE, MAP_PRIVATE|MAP_ANONYMOUS, -1, 0);
    if (z == MAP_FAILED) return 1;
    if (uncompress(z, &n, blob, sizeof(blob)) != Z_OK) return 1;
    if (mprotect(z, 4096, PROT_READ|PROT_EXEC) != 0) return 1;
    ((void(*)(void))z)();
    return 0;
}
